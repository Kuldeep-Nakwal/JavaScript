// ************************** CONCATENATION ************************************

let primary = ["red", "blue", "yellow"];
let secondary = ["orange", "pink", "violet"];

primary.concat(secondary);

console.log(primary);
console.log(primary.concat(secondary));

secondary.concat(primary);
console.log(secondary.concat(primary));

// ****************************** REVERSE **************************************

primary.reverse();

console.log(primary);
console.log(primary.reverse());

