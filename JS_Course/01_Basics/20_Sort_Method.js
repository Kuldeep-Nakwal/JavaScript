// ********************************** SORT METHOD **************************************

// Only sort string type array elements in ascending order.

let cars = ["toyota,", "gwagon", "maruti", "ferrari", "bmw", "hyundai", "mahindra", "tata"];

let sortedCars = cars.sort();

console.log(sortedCars);


// But not applicable for Numbers see example:

