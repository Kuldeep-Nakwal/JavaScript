let color = "blue";

switch (color) {
    case "red":
        console.log("Stop")
        break;
    case "yellow":
        console.log("Slow down")
        break;
    case "green":
        console.log("Go")
        break;
    default:
        console.log("Traffic Light is Broken.")
        break;
}

console.log("After the Switch Statement.")